/** 학년군 순서. 선수는 후속과 같거나 낮은 학년군이어야 한다. */
const BAND_ORDER = { '1-2': 1, '3-4': 2, '5-6': 3 };

/**
 * 그래프 검증. 스파인과 대조해 다음을 확인한다.
 *   1. 모든 수학 성취기준이 목록에 있다 (누락 없음)
 *   2. 모든 선수 코드가 실재한다 (허깨비 참조 없음)
 *   3. 순환이 없다 (DAG)
 *   4. 선수의 학년군이 후속보다 높지 않다 (시간 역행 없음)
 */
export function validatePrerequisites(spine) {
  const mathStandards = spine.standards.filter((s) => s.subject === 'math');
  const bandOf = new Map(mathStandards.map((s) => [s.code, s.gradeBand]));
  const problems = [];

  for (const std of mathStandards) {
    if (!Object.hasOwn(MATH_PREREQUISITES, std.code)) {
      problems.push({ kind: 'missing', code: std.code, message: '선수 관계 목록에 없다' });
    }
  }
  for (const code of Object.keys(MATH_PREREQUISITES)) {
    if (!bandOf.has(code)) {
      problems.push({ kind: 'unknown-code', code, message: '스파인에 없는 성취기준' });
    }
  }

  for (const [code, prereqs] of Object.entries(MATH_PREREQUISITES)) {
    for (const p of prereqs) {
      if (!bandOf.has(p)) {
        problems.push({ kind: 'unknown-prereq', code, message: `실재하지 않는 선수 ${p}` });
        continue;
      }
      if (p === code) {
        problems.push({ kind: 'self-loop', code, message: '자기 자신을 선수로 둔다' });
        continue;
      }
      const from = BAND_ORDER[bandOf.get(p)];
      const to = BAND_ORDER[bandOf.get(code)];
      if (from > to) {
        problems.push({
          kind: 'grade-inversion',
          code,
          message: `선수 ${p}(${bandOf.get(p)})가 ${code}(${bandOf.get(code)})보다 높은 학년군이다`,
        });
      }
    }
  }

  // 순환 검출: 색칠 기반 깊이 우선 탐색
  const WHITE = 0;
  const GRAY = 1;
  const BLACK = 2;
  const color = new Map(Object.keys(MATH_PREREQUISITES).map((c) => [c, WHITE]));
  const stack = [];
  const visit = (code) => {
    color.set(code, GRAY);
    stack.push(code);
    for (const p of MATH_PREREQUISITES[code] ?? []) {
      if (!color.has(p)) continue;
      if (color.get(p) === GRAY) {
        problems.push({
          kind: 'cycle',
          code,
          message: `순환: ${[...stack.slice(stack.indexOf(p)), p].join(' -> ')}`,
        });
        continue;
      }
      if (color.get(p) === WHITE) visit(p);
    }
    stack.pop();
    color.set(code, BLACK);
  };
  for (const code of Object.keys(MATH_PREREQUISITES)) {
    if (color.get(code) === WHITE) visit(code);
  }

  const edgeCount = Object.values(MATH_PREREQUISITES).reduce((s, v) => s + v.length, 0);
  const roots = Object.entries(MATH_PREREQUISITES).filter(([, v]) => v.length === 0).map(([c]) => c);
  const crossBand = Object.entries(MATH_PREREQUISITES).flatMap(([code, ps]) =>
    ps.filter((p) => bandOf.has(p) && bandOf.get(p) !== bandOf.get(code))).length;

  return {
    standardCount: mathStandards.length,
    listedCount: Object.keys(MATH_PREREQUISITES).length,
    edgeCount,
    crossBandEdges: crossBand,
    rootCount: roots.length,
    roots,
    problems,
  };
}

/**
 * 한 기준의 선수를 깊이 우선으로 모두 모은다.
 * 취약 기준에서 거슬러 올라가 복습 순서를 만드는 데 쓴다.
 * 반환 순서는 먼 선수부터(먼저 배워야 하는 것부터)다.
 */
export function ancestorsOf(code, { maxDepth = Number.POSITIVE_INFINITY } = {}) {
  const seen = new Set();
  const depthOf = new Map();
  const walk = (current, depth) => {
    if (depth > maxDepth) return;
    for (const p of MATH_PREREQUISITES[current] ?? []) {
      const known = depthOf.get(p);
      if (known === undefined || depth < known) depthOf.set(p, depth);
      if (seen.has(p)) continue;
      seen.add(p);
      walk(p, depth + 1);
    }
  };
  walk(code, 1);
  return [...seen].sort((a, b) => (depthOf.get(b) - depthOf.get(a)) || a.localeCompare(b));
}

/** 이 기준을 선수로 두는 후속 기준들. 무엇이 막혀 있는지 보여 준다. */
export function dependentsOf(code) {
  return Object.entries(MATH_PREREQUISITES)
    .filter(([, ps]) => ps.includes(code))
    .map(([c]) => c)
    .sort();
}

/**
 * 학습 순서. 선수를 먼저 두는 위상 정렬이다.
 * 같은 층 안에서는 코드 순서로 안정 정렬해 결과가 결정적이다.
 */
export function learningOrder(codes = Object.keys(MATH_PREREQUISITES)) {
  const target = new Set(codes);
  const depth = new Map();
  const compute = (code, guard = new Set()) => {
    if (depth.has(code)) return depth.get(code);
    if (guard.has(code)) return 0;
    guard.add(code);
    const prereqs = (MATH_PREREQUISITES[code] ?? []).filter((p) => Object.hasOwn(MATH_PREREQUISITES, p));
    const d = prereqs.length === 0 ? 0 : Math.max(...prereqs.map((p) => compute(p, guard))) + 1;
    guard.delete(code);
    depth.set(code, d);
    return d;
  };
  for (const code of Object.keys(MATH_PREREQUISITES)) compute(code);
  return [...target].sort((a, b) => (depth.get(a) - depth.get(b)) || a.localeCompare(b));
}
