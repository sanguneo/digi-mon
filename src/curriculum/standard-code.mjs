/**
 * 성취기준 코드 형식 하나.
 *
 * 2022 개정 교육과정 초등 코드는 [학년군 끝학년 + 교과 + 영역 두 자리 - 순번 두
 * 자리] 다. 예: [2수01-06]. 학년군 끝학년은 2·4·6 뿐이고 교과는 국·수·영 뿐이다.
 *
 * 같은 규칙이 네 곳에 두 패턴으로 흩어져 있었다. 옵션 파서·학습 게이트·응답
 * 기록은 엄격형이었고, 생성기 계약(`engine/registry.mjs`)만 느슨형
 * /^\[\d[가-힣]+\d{2}-\d{2}\]$/ 였다. 느슨형은 [1수01-01] 이나 [3과01-01] 처럼
 * 존재하지 않는 코드를 통과시키므로, 등록은 되는데 옵션 파서가 거부하는 생성기가
 * 조용히 생길 수 있었다. 엄격형 하나로 모은다 — 좁히기 전에 등록된 생성기 193개와
 * 스파인 248기준의 코드가 전부 엄격형에 맞는 것을 확인했다.
 */
export const STANDARD_CODE_RE = /^\[[246][국수영]\d{2}-\d{2}\]$/;

export function isStandardCode(value) {
  return typeof value === 'string' && STANDARD_CODE_RE.test(value);
}
